"""Non-MHC shotgun proteomics corpus (MS detectability + excision).

This loader supplies observed-product and wrong-enzyme proxy labels. It does
not supply detectability targets: the raw observation table does not establish
search-space membership, comparable protocols or independent replicate counts.
Fraction counts alone cannot establish first-seen depth or a detectability
probability (presto#70, hitlist#654).

``excision_label``
    Whether machinery ``M`` would produce this peptide. Positives are the
    peptides an arm actually observed. Negatives are generated by relabeling a
    peptide with an enzyme whose cleavage rule its termini violate — a
    chymotryptic peptide ending in F is not something GluC would produce. The
    rule-derived labels are generated controls, not measured negative outcomes.

Two limitations, deliberate and recorded.

Bulk rows carry no flanking sequence, because ``load_bulk_peptides`` returns
peptide coordinates (``uniprot_acc``, ``start_position``, ``end_position``) but
not the source protein sequence. So ``s_N`` sees ``<MISSING>`` on this branch
and the excision signal is carried by ``s_C`` alone. That is the correct
half: the C-terminal junction is where the protease rule lives. Wiring the
proteome in would light up ``s_N`` as well.

Second: ``detectability_label`` stays missing for every imported observation
and generated control. ``protein_sequences`` does not generate candidates.
The verified ``scoped_bulk`` adapter consumes Hitlist's frozen candidate export
and preserves its manifest. Passing an arbitrary protein dictionary to this raw
loader cannot establish a historical search space. See presto#70 and hitlist#681.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from typing import Any, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

from .vocab import (
    EXCISION_MACHINERY_TO_IDX,
    EXCISION_P1_PRIME_BLOCKED,
    EXCISION_P1_RULES,
    is_encodable_sequence,
    is_missing_scalar,
)

# hitlist's canonical enzyme strings -> Presto machinery names.
ENZYME_TO_MACHINERY = {
    "Trypsin/P (cleaves K/R except before P)": "trypsin",
    "Trypsin/P": "trypsin",
    "Trypsin": "trypsin",
    "Chymotrypsin": "chymotrypsin",
    "LysC": "lysc",
    "GluC": "gluc",
}


@dataclass
class BulkMSRecord:
    """One shotgun-MS observation or in-silico candidate."""

    peptide: str
    machinery: str = "trypsin"
    flank_n: str = ""
    flank_c: str = ""
    detectability_label: Optional[float] = None
    excision_label: Optional[float] = None
    protein_id: str = ""
    cell_line: str = ""
    n_fractions: Optional[int] = None
    n_replicates_detected: Optional[int] = None
    observed: bool = True
    source: str = "bulk_proteomics"
    acquisition: Dict[str, Any] = field(default_factory=dict)
    generated_kind: str = ""
    flank_n_is_terminus: bool = False
    flank_c_is_terminus: bool = False
    # Verified scoped evidence, retained only as host metadata.
    evidence_row_id: str = ""
    reference_iri: str = ""
    source_bundle_id: str = ""
    source_partition: str = ""
    source_endpoint: str = ""
    source_units: str = ""
    pmid: str = ""
    doi: str = ""
    scoped_peptide_id: str = ""
    candidate_id: str = ""
    candidate_lookup_key: str = ""
    source_n_candidate_occurrences: str = ""
    source_label_evidence: str = ""
    source_search_space_id: str = ""
    source_protocol_id: str = ""
    source_reference_sha256: str = ""
    source_parent_assignment_basis: str = ""


#: Case-folded view of ENZYME_TO_MACHINERY, built once.
_ENZYME_TO_MACHINERY_FOLDED = {
    key.strip().lower(): value for key, value in ENZYME_TO_MACHINERY.items()
}


def machinery_for_enzyme(enzyme: str) -> str:
    """Map a hitlist ``digestion_enzyme`` string to a machinery name.

    Case-insensitive. The lookup used to be exact, and the corpus happens to
    write "Trypsin/P (cleaves K/R except before P)" and "LysC" with exactly the
    capitalization in the table -- so it worked, by luck. A lowercase export, a
    hitlist schema change or a hand-written test row would have mapped every
    enzyme to "unknown", and rows with unknown machinery are silently skipped,
    so the entire shotgun corpus would vanish with no error.
    """
    return _ENZYME_TO_MACHINERY_FOLDED.get(str(enzyme or "").strip().lower(), "unknown")


def _optional_count(value) -> Optional[int]:
    """Preserve unknown observation metadata without inventing zero counts."""
    if is_missing_scalar(value) or (isinstance(value, str) and not value.strip()):
        return None
    return int(value)


def would_cleave(machinery: str, p1: str, p1_prime: str) -> bool:
    """Whether ``machinery`` cuts C-terminal to ``p1`` given the next residue.

    Only defined for the in-vitro proteases, whose rules are exact. Returns
    ``True`` for in-vivo machinery, which has no hard rule.
    """
    rule = EXCISION_P1_RULES.get(machinery)
    if rule is None:
        return True
    if p1 not in rule:
        return False
    blocked = EXCISION_P1_PRIME_BLOCKED.get(machinery, "")
    return not (p1_prime and blocked and p1_prime in blocked)


def _mismatched_machinery(
    peptide: str, c_flank: str, true_machinery: str, rng: random.Random
) -> Optional[str]:
    """Pick an enzyme whose rule this peptide's C-terminus violates."""
    if not peptide:
        return None
    p1 = peptide[-1]
    p1_prime = c_flank[0] if c_flank else ""
    candidates = [
        name
        for name in EXCISION_P1_RULES
        if name != true_machinery and not would_cleave(name, p1, p1_prime)
    ]
    if not candidates:
        return None
    return rng.choice(candidates)


def _iter_frame_rows(frame, chunk_size: int = 50_000):
    """Yield row dicts in chunks rather than materializing the whole frame."""
    n_rows = len(frame)
    for start in range(0, n_rows, chunk_size):
        for row in frame.iloc[start : start + chunk_size].to_dict("records"):
            yield row


def records_from_bulk_frame(
    frame,
    *,
    max_records: Optional[int] = None,
    excision_negative_ratio: float = 1.0,
    seed: int = 42,
) -> Tuple[List[BulkMSRecord], Dict[str, Any]]:
    """Build bulk records from a hitlist ``load_bulk_peptides`` frame.

    Expected columns: ``peptide``, ``digestion_enzyme``, ``cell_line_name``,
    ``uniprot_acc``, ``n_fractions_in_run``, ``n_replicates_detected``.
    """
    rng = random.Random(seed)
    # Stream by default. `to_dict("records")` materializes one dict per row for
    # the whole bulk-proteomics table up front, which is the memory profile
    # `hitlist_source._iter_row_dicts` exists to avoid. Only the capped path
    # needs a concrete sequence, because rng.sample must index it.
    if hasattr(frame, "to_dict"):
        if max_records is not None and max_records > 0:
            rows = frame.to_dict("records")
            if max_records < len(rows):
                rows = rng.sample(rows, max_records)
        else:
            rows = _iter_frame_rows(frame)
    else:
        rows = list(frame)
        if max_records is not None and 0 < max_records < len(rows):
            rows = rng.sample(rows, max_records)

    records: List[BulkMSRecord] = []
    machinery_counts: Dict[str, int] = {}
    n_excision_negatives = 0
    n_unencodable_peptides = 0

    for row in rows:
        peptide = str(row.get("peptide") or "").strip().upper()
        # Same policy as the hitlist adapter: a peptide the tokenizer cannot
        # represent is dropped here rather than raising deep inside collation
        # partway through an epoch. Shotgun peptides come from whole-proteome
        # digests, so genuine-but-unmodelled residues (selenocysteine) do occur.
        if not is_encodable_sequence(peptide):
            n_unencodable_peptides += 1
            continue
        machinery = machinery_for_enzyme(row.get("digestion_enzyme"))
        if machinery == "unknown":
            continue
        machinery_counts[machinery] = machinery_counts.get(machinery, 0) + 1
        records.append(
            BulkMSRecord(
                peptide=peptide,
                machinery=machinery,
                detectability_label=None,
                # Observed-product proxy; this does not isolate cleavage
                # from abundance, assignment or acquisition effects.
                excision_label=1.0,
                protein_id=str(row.get("uniprot_acc") or ""),
                cell_line=str(row.get("cell_line_name") or ""),
                n_fractions=_optional_count(row.get("n_fractions_in_run")),
                n_replicates_detected=_optional_count(row.get("n_replicates_detected")),
                observed=True,
            )
        )

        if excision_negative_ratio > 0 and rng.random() < excision_negative_ratio:
            wrong = _mismatched_machinery(peptide, "", machinery, rng)
            if wrong is not None:
                n_excision_negatives += 1
                records.append(
                    BulkMSRecord(
                        peptide=peptide,
                        machinery=wrong,
                        # Excision only: the peptide exists, but not as a
                        # product of this enzyme. Detectability is unlabeled
                        # here because it is the same molecule either way.
                        detectability_label=None,
                        excision_label=0.0,
                        protein_id=str(row.get("uniprot_acc") or ""),
                        cell_line=str(row.get("cell_line_name") or ""),
                        observed=False,
                        generated_kind="bulk_wrong_enzyme",
                    )
                )

    stats = {
        "n_records": len(records),
        "n_observed": sum(1 for r in records if r.observed),
        "n_excision_negatives": n_excision_negatives,
        "n_detectability_labels": 0,
        "detectability_status": "unavailable_without_verified_search_scope",
        "machinery_counts": dict(sorted(machinery_counts.items(), key=lambda kv: -kv[1])),
        # Dropped rows must be visible: a corpus where selenocysteine-bearing
        # peptides silently vanish would otherwise report identical stats to
        # one where they never existed.
        "n_unencodable_peptides": n_unencodable_peptides,
    }
    return records, stats


def load_bulk_ms_records(
    *,
    cell_line: Optional[str] = None,
    digestion_enzyme: Optional[Sequence[str]] = None,
    max_records: Optional[int] = None,
    excision_negative_ratio: float = 1.0,
    protein_sequences: Optional[Mapping[str, str]] = None,
    seed: int = 42,
) -> Tuple[List[BulkMSRecord], Dict[str, Any]]:
    """Load bulk shotgun records from hitlist.

    ``protein_sequences`` is accepted for the in-silico-negative path
    (hitlist#361); passing it currently has no effect beyond being recorded in
    the returned stats. This raw-table path produces no detectability labels.
    """
    try:
        from hitlist.bulk_proteomics import load_bulk_peptides
    except ImportError as exc:  # pragma: no cover - exercised via install docs
        raise SystemExit(
            "hitlist is required for the bulk MS corpus. Install it with `pip install hitlist`."
        ) from exc

    kwargs: Dict[str, Any] = {}
    if cell_line is not None:
        kwargs["cell_line"] = cell_line
    if digestion_enzyme is not None:
        kwargs["digestion_enzyme"] = list(digestion_enzyme)
    frame = load_bulk_peptides(**kwargs)

    records, stats = records_from_bulk_frame(
        frame,
        max_records=max_records,
        excision_negative_ratio=excision_negative_ratio,
        seed=seed,
    )
    stats["protein_sequences_supplied"] = protein_sequences is not None
    stats["in_silico_negatives_available"] = False
    return records, stats


def machinery_index(name: str) -> int:
    """Vocabulary index for a machinery name."""
    return EXCISION_MACHINERY_TO_IDX.get(name, EXCISION_MACHINERY_TO_IDX["unknown"])


def dual_corpus_transfer_set(
    mhc_peptides: Iterable[str],
    bulk_records: Sequence[BulkMSRecord],
) -> Tuple[List[BulkMSRecord], Dict[str, Any]]:
    """Select overlapping peptide sequences without qualifying their labels.

    Returns bulk records whose peptide occurs in ``mhc_peptides`` and a length
    histogram. This selection preserves missing detectability labels and
    generated controls. Overlap alone does not provide a detectability target
    or establish independent held-out evaluation; the raw bulk path supplies
    no such targets. A transfer evaluation needs verified search-scoped labels
    and a separately audited split (presto#70/#71).
    """
    wanted = {str(p).strip().upper() for p in mhc_peptides if str(p).strip()}
    overlap = [r for r in bulk_records if r.peptide.upper() in wanted]
    lengths: Dict[int, int] = {}
    for record in overlap:
        lengths[len(record.peptide)] = lengths.get(len(record.peptide), 0) + 1
    stats = {
        "n_mhc_peptides": len(wanted),
        "n_bulk_records": len(bulk_records),
        "n_overlap_records": len(overlap),
        "n_overlap_peptides": len({r.peptide.upper() for r in overlap}),
        "length_histogram": dict(sorted(lengths.items())),
    }
    return overlap, stats
